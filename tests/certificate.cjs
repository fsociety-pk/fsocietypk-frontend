const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const Module = require('node:module');
const file = path.resolve(__dirname, '../src/utils/certificateGenerator.ts');
const compiled = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const moduleUnderTest = new Module(file, module);
moduleUnderTest._compile(compiled, file);
const { generateCertificateSVG } = moduleUnderTest.exports;
const data = { userName: 'A Very Long Certificate Recipient Name', challengeName: 'Advanced web forensics '.repeat(20), completionDate: new Date('2025-01-02T12:00:00Z'), totalChallenges: 5, platformName: 'Fsociety PK', platformURL: 'https://fsocietypk.tech' };
const svg = generateCertificateSVG(data);
assert(svg.includes('02 January 2025'));
assert(svg.includes('…'), 'extreme titles truncate visibly');
assert(svg.includes('y="744"'), 'three-line title leaves summary above metadata');
assert(!svg.includes('y="746"'), 'no fourth title line');
const unsafe = generateCertificateSVG({ ...data, userName: '<script>alert("x")</script>', challengeName: 'A & B < C', completionDate: null });
assert(!unsafe.includes('<script>'));
assert(unsafe.includes('&lt;script&gt;'));
assert(unsafe.includes('A &amp; B &lt; C'));
assert(unsafe.includes('Date unavailable'));
const output = path.resolve(__dirname, '../../.playwright-mcp/certificate-long.svg');
fs.writeFileSync(output, svg);
fs.writeFileSync(path.resolve(__dirname, '../../.playwright-mcp/certificate-module.mjs'), ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText);
console.log('PASS certificate recorded/unknown date, escaped text and long-title bounds. Preview: ' + output);
