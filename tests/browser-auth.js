// Requires browser-fixtures.js; this verifies frontend behavior with mock API responses.
async (page) => {
  const checks = [];
  const assert = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  assert(await page.getByLabel('Email address').getAttribute('aria-invalid') === 'true', 'Email is required');
  await page.getByLabel('Username', { exact: true }).fill("' OR '1'='1");
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  assert((await page.getByRole('alert').innerText()).includes('Bobby Tables'), 'Playful payload response precedes validation');
  await page.getByLabel('Email address').fill('fixture@example.invalid');
  await page.getByLabel('Username', { exact: true }).fill('fixture_user');
  await page.getByLabel('Password', { exact: true }).fill('weak');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  assert(await page.getByLabel('Password', { exact: true }).getAttribute('aria-invalid') === 'true', 'Weak password rejected');
  await page.getByLabel('Password', { exact: true }).fill('FixturePassword1!');
  assert(await page.locator('.password-checker li.met').count() === 5, 'All five live password checks pass');
  await page.getByRole('button', { name: 'Show password', exact: true }).click();
  assert(await page.getByLabel('Password', { exact: true }).getAttribute('type') === 'text', 'Password visibility toggle works');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.getByRole('heading', { name: 'One last checkpoint.' }).waitFor();
  assert(await page.getByRole('button', { name: /Resend in/ }).isDisabled(), 'OTP resend cooldown disables button');
  const pending = await page.evaluate(() => JSON.parse(sessionStorage.getItem('fsociety-pending-email')));
  assert(!('password' in pending) && pending.registrationId, 'Pending storage excludes password');
  await page.getByLabel('Email verification code').fill('000000');
  await page.getByRole('button', { name: /Verify email/ }).click();
  await page.getByRole('alert').waitFor();
  assert((await page.getByRole('alert').innerText()).includes('incorrect'), 'Incorrect OTP is shown');
  await page.evaluate(() => { const p = JSON.parse(sessionStorage.getItem('fsociety-pending-email')); p.resendAt = Date.now() - 1000; sessionStorage.setItem('fsociety-pending-email', JSON.stringify(p)); });
  await page.reload();
  await page.getByRole('button', { name: 'Resend code', exact: true }).click();
  assert(await page.getByRole('button', { name: /Resend in/ }).isDisabled(), 'Resend refreshes cooldown');
  await page.getByLabel('Email verification code').fill('123456');
  await page.getByRole('button', { name: /Verify email/ }).click();
  await page.waitForURL('**/dashboard');
  assert(await page.evaluate(() => sessionStorage.getItem('fsociety-pending-email')) === null, 'Successful verification clears pending registration');
  await page.locator('.sidebar-footer').getByRole('button', { name: 'Sign out' }).click();
  await page.waitForURL('**/login');
  await page.getByRole('heading', { name: 'Welcome back.' }).waitFor();
  await page.getByRole('navigation', { name: 'Account access' }).getByRole('link', { name: 'Sign up' }).click();
  await page.getByRole('heading', { name: 'Join the collective.' }).waitFor();
  await page.getByRole('navigation', { name: 'Account access' }).getByRole('link', { name: 'Log in' }).click();
  await page.getByRole('heading', { name: 'Welcome back.' }).waitFor();
  checks.push('Login/signup navigation transitions complete');
  await page.getByLabel('Username or email').fill('fixture@example.invalid');
  await page.getByLabel('Password', { exact: true }).fill('FixturePassword1!');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.waitForURL('**/dashboard');
  assert(await page.locator('.app-sidebar').isVisible(), 'Email login enters authenticated workspace');
  return { mode: 'mock API', checks };
}
