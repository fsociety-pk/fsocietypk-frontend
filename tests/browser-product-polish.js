// Run after browser-fixtures.js. All API responses are intercepted.
async (page) => {
  const checks = [];
  const assert = (ok, label) => { if (!ok) throw new Error(label); checks.push(label); };
  const introKey = 'fsociety-cinematic-intro-v1';
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(async () => {
    localStorage.removeItem('fsocietypk-auth'); localStorage.setItem('fsociety-theme', 'light'); sessionStorage.clear();
    await fetch('/__fixture', { method: 'POST', body: JSON.stringify({ authenticated: false }) });
  });
  await page.goto('http://fsociety.test/signup');
  const username = page.getByLabel('Username', { exact: true });
  await username.fill('sheriff');
  assert(await page.locator('.username-ideas button').count() === 3, 'Signup offers three username ideas');
  assert((await page.locator('.companion-bubble').innerText()).includes('sheriff_ops'), 'The crew suggests a username');
  assert((await page.locator('.username-ideas small').innerText()).includes('check its availability'), 'Ideas do not promise availability');
  for (const width of [320,390]) {
    await page.setViewportSize({ width, height: 844 });
    await username.fill('mmmmmmmmmmmmmmmmmmmm');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Long username ideas fit ${width}px`);
    assert(await page.evaluate(() => document.querySelector('.companion-bubble').getBoundingClientRect().bottom < document.querySelector('.companion-antenna').getBoundingClientRect().top - 3), `Suggestion bubble stays above the crew at ${width}px`);
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await username.fill('sheriff');
  await username.press('Tab');
  assert(await page.locator('.username-ideas button').first().evaluate(el => el === document.activeElement), 'Keyboard can reach username ideas');
  await page.locator('.username-ideas button').first().press('Enter');
  assert(await username.inputValue() === 'sheriff_ops', 'Choosing a suggestion fills the username');
  assert(await username.evaluate(el => el === document.activeElement), 'Choosing a suggestion returns focus to the input');
  assert(await page.locator('.username-ideas').count() === 0, 'Chosen suggestions close');
  await page.locator('.username-availability.is-available').waitFor();
  assert((await page.locator('.companion-bubble').innerText()).includes('Nice choice'), 'The crew confirms the chosen username');
  const password = page.getByLabel('Password', { exact: true });
  await password.fill('weak');
  assert(await page.locator('.access-companions').getAttribute('data-emotion') === 'sad', 'Weak passwords make the crew sad');
  assert(await page.locator('.companion-mouth').first().evaluate(el => getComputedStyle(el).transform !== 'none'), 'Sadness changes the visible mouth');
  await password.fill('StrongPassword1!');
  assert(await page.locator('.access-companions').getAttribute('data-emotion') === 'happy', 'Strong passwords make the crew happy');
  assert(await page.locator('.companion-mouth').first().evaluate(el => getComputedStyle(el, '::after').content !== 'none'), 'Happy faces have a toothy smile');
  await page.setViewportSize({ width: 320, height: 844 });
  assert(await page.evaluate(() => document.querySelector('.companion-bubble').getBoundingClientRect().bottom < document.querySelector('.companion-antenna').getBoundingClientRect().top - 3), 'Wrapped password feedback stays above the crew');
  await page.setViewportSize({ width: 1440, height: 900 });
  await password.fill('');
  assert(await page.locator('.access-companions').getAttribute('data-emotion') === 'neutral', 'Clearing the password resets emotion');
  await username.fill("' OR '1'='1");
  assert(await page.locator('#username-error').count() === 0, 'Signup does not warn about SQL while typing');
  assert(!/sql|payload/i.test(await page.locator('.companion-bubble').innerText()), 'The mascot does not reveal the SQL prank early');
  assert(await page.locator('.username-ideas').count() === 0, 'Payloads do not generate username suggestions');
  await page.getByRole('navigation', { name: 'Account access' }).getByRole('link', { name: 'Log in', exact: true }).click();
  await page.getByLabel('Username or email').fill('sheriff');
  assert(await page.locator('.username-ideas').count() === 0, 'Login never offers signup username ideas');
  await page.getByLabel('Username or email').fill("' OR '1'='1");
  assert(await page.locator('#username-error').count() === 0, 'Login does not warn about SQL while typing');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.getByRole('heading', { name: 'Logging in as admin…', exact: true }).waitFor();
  assert(await page.locator('.access-companions').count() === 0, 'Connecting prank has no cartoons');
  await page.getByRole('heading', { name: 'Lol! Did you think that worked?', exact: true }).waitFor();
  assert(await page.locator('.access-companions').count() === 0, 'Prank reveal has no cartoons');
  assert((await page.locator('.sql-prank-description').innerText()).includes('Bobby Tables'), 'Updated prank punchline is shown');
  const requests = await page.evaluate(async () => (await (await fetch('/__fixture')).json()).data.requests);
  assert(!requests.some(request => /\/auth\/(login|register)$/.test(request.path)), 'Suggestions and prank send no credential requests');
  await page.getByRole('button', { name: 'Back to login', exact: true }).click();
  await page.getByRole('button', { name: 'Switch to dark theme', exact: true }).click();
  assert(await page.locator('.brand-artwork').first().evaluate(img => getComputedStyle(img).backgroundColor !== 'rgba(0, 0, 0, 0)'), 'Dark logo gets a contrasting base');
  await page.locator('.brand-lockup').screenshot({ path: '/tmp/polish-logo-dark.png' });
  await page.evaluate(async () => {
    await fetch('/__fixture', { method: 'POST', body: JSON.stringify({ authenticated: true }) });
    localStorage.setItem('fsocietypk-auth', JSON.stringify({ state: { user: { _id: '507f1f77bcf86cd799439011', username: 'obsidian', role: 'user' }, isAuthenticated: true }, version: 0 }));
  });
  await page.goto('http://fsociety.test/dashboard');
  await page.locator('.action-card').first().waitFor();
  for (const theme of ['light', 'dark']) {
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme; }, theme);
    assert(await page.locator('.action-card').first().evaluate(el => getComputedStyle(el).backgroundColor !== getComputedStyle(document.body).backgroundColor), `${theme} cards differ from the page`);
    assert(await page.locator('.action-card').evaluateAll(cards => new Set(cards.map(card => getComputedStyle(card).backgroundColor)).size >= 2), `${theme} cards have distinct colored surfaces`);
    await page.screenshot({ path: `/tmp/polish-cards-${theme}.png`, fullPage: true });
  }
  await page.locator('.action-card').first().hover();
  await page.waitForFunction(() => new DOMMatrixReadOnly(getComputedStyle(document.querySelector('.action-card')).transform).m42 < -3);
  checks.push('Cards lift on hover');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert(await page.locator('.action-card').first().evaluate(el => getComputedStyle(el).transform === 'none'), 'Reduced motion disables card movement');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.evaluate(async key => {
    await fetch('/__fixture', { method: 'POST', body: JSON.stringify({ authenticated: false }) });
    localStorage.removeItem('fsocietypk-auth'); sessionStorage.removeItem(key);
  }, introKey);
  await page.goto('http://fsociety.test/');
  const intro = page.getByRole('dialog', { name: 'Welcome to Fsociety PK', exact: true });
  await intro.waitFor();
  assert(await intro.getByText('Hello Friends', { exact: true }).isVisible(), 'Splash starts with Hello Friends');
  assert(await page.locator('#root').evaluate(el => el.inert), 'Splash keeps background controls out of focus');
  await page.waitForTimeout(350);
  await page.screenshot({ path: '/tmp/polish-splash-first.png' });
  await intro.getByText('Welcome to the Fsociety PK', { exact: true }).waitFor();
  checks.push('Splash changes to Welcome to the Fsociety PK');
  await page.waitForTimeout(400);
  await page.screenshot({ path: '/tmp/polish-splash-second.png' });
  await intro.waitFor({ state: 'hidden' });
  assert(await page.locator('#root').evaluate(el => !el.inert), 'Splash restores background interaction');
  assert(await page.evaluate(() => document.body.style.overflow !== 'hidden'), 'Splash restores scrolling');
  await page.reload(); await page.locator('.cinematic-landing').waitFor();
  assert(await page.locator('.cinematic-intro').count() === 0, 'Splash plays once per session');
  await page.evaluate(key => sessionStorage.removeItem(key), introKey); await page.reload();
  await page.getByRole('button', { name: 'Skip intro', exact: true }).click();
  assert(await page.locator('.cinematic-intro').count() === 0, 'Splash can be skipped');
  await page.evaluate(key => sessionStorage.removeItem(key), introKey); await page.reload();
  await page.getByRole('button', { name: 'Skip intro', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  assert(await page.locator('.cinematic-intro').count() === 0, 'Escape dismisses the splash');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.evaluate(key => sessionStorage.removeItem(key), introKey); await page.reload();
  await page.locator('.cinematic-landing').waitFor();
  assert(await page.locator('.cinematic-intro').count() === 0, 'Reduced motion skips the cinematic intro');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto('http://fsociety.test/login'); await page.locator('.login-mode').waitFor();
  assert(await page.locator('.cinematic-intro').count() === 0, 'Direct account access does not play the splash');
  return { mode: 'mock API', checks };
}
