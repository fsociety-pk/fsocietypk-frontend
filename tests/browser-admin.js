  const checks = [];
  const assert = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  const go = async path => { await page.goto('http://fsociety.test' + path); await page.waitForLoadState('networkidle'); };
  const fixture = async value => page.evaluate(async value => (await (await fetch('/__admin-fixture', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(value) })).json()), value);
  const state = async () => page.evaluate(async () => (await (await fetch('/__admin-fixture')).json()));
  page.removeAllListeners('dialog');
  page.on('dialog', dialog => dialog.accept());
  await page.setViewportSize({ width: 1440, height: 1000 });
  await go('/admin');
  await page.getByRole('heading', { name: 'Platform overview', exact: true }).waitFor();
  assert(await page.locator('.app-sidebar, .user-chip').count() === 0, 'Admin has a dedicated shell without member navigation or profile button');
  assert(!(await page.locator('.admin-nav').first().innerText()).match(/My submissions|My profile|Hall of Fame/), 'No player tasks appear in admin navigation');
  assert(await page.locator('.admin-stat').count() === 4 && (await page.locator('.admin-stat-row').innerText()).includes('1,284'), 'Overview uses real API response values');
  await page.screenshot({ path: '/tmp/admin-overview-light.png', fullPage: true, animations: 'disabled' });
  await go('/dashboard'); await page.waitForURL('**/admin'); checks.push('Admin is redirected away from member dashboard');
  await go('/admin/challenges?status=pending');
  assert(await page.locator('article').count() === 2, 'Pending challenge filter works');
  await page.getByRole('link', { name: 'Review & edit', exact: true }).first().click();
  await page.getByLabel('Title', { exact: true }).fill('The Forgotten Endpoint, revised');
  await Promise.all([page.waitForResponse(response => response.url().includes('/admin/challenges/') && response.request().method() === 'PATCH'), page.getByRole('button', { name: 'Save changes', exact: true }).click()]);
  assert((await state()).requests.some(r => r.method === 'PATCH' && r.body.title === 'The Forgotten Endpoint, revised'), 'Challenge metadata edits use admin endpoint');
  await page.getByRole('button', { name: 'Publish saved version', exact: true }).click();
  await page.getByRole('button', { name: 'Publish saved version', exact: true }).waitFor({ state: 'hidden' });
  checks.push('Challenge publishing works');
  await go('/admin/challenges/new');
  await page.locator('#challenge-title').fill('Browser-created challenge');
  await page.locator('#challenge-description').fill('Investigate the evidence and uncover the hidden flag in this challenge.');
  await page.locator('#challenge-category').selectOption('web');
  await page.locator('#challenge-difficulty').selectOption('easy');
  await page.locator('#challenge-flag').fill('fsociety{browser_fixture}');
  await page.getByRole('button', { name: 'Publish challenge', exact: true }).click();
  await page.getByRole('heading', { name: 'Challenge published', exact: true }).waitFor();
  assert((await state()).requests.some(r => r.path.endsWith('/admin/challenges') && r.method === 'POST'), 'Admin can create and publish a challenge');
  await go('/admin/users');
  await page.getByRole('searchbox', { name: 'Search members by username or email' }).fill('cipher');
  await page.waitForResponse(response => response.url().includes('/admin/users') && response.url().includes('search=cipher'));
  assert(await page.locator('tbody tr').count() === 1, 'Member search is performed by server across account data');
  await page.getByRole('button', { name: 'Suspend', exact: true }).click();
  await page.getByRole('button', { name: 'Restore access', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Restore access', exact: true }).click();
  await page.getByRole('button', { name: 'Suspend', exact: true }).waitFor(); checks.push('Member suspension and restoration work');
  await go('/admin/reviews?tab=writeups');
  await page.getByRole('button', { name: 'Approve', exact: true }).click();
  await page.getByRole('heading', { name: "You're all caught up", exact: true }).waitFor();
  await page.getByLabel('Show', { exact: true }).selectOption('approved');
  await page.getByRole('heading', { name: 'Finding the forgotten endpoint', exact: true }).waitFor(); checks.push('Writeup moderation and published filter work');
  await go('/admin/reviews?tab=resources');
  await page.getByRole('button', { name: 'Approve resource', exact: true }).click();
  await page.getByRole('heading', { name: "You're all caught up", exact: true }).waitFor(); checks.push('Resource queue deep link and approval work');
  await go('/admin/projects');
  await page.getByRole('button', { name: 'Edit project', exact: true }).click();
  await page.getByLabel('Title', { exact: true }).fill('Recon workspace updated');
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  await page.getByRole('heading', { name: 'Recon workspace updated', exact: true }).waitFor(); checks.push('Project editing works');
  await go('/admin/settings');
  await page.getByLabel('Title', { exact: true }).fill('Staff briefing');
  await page.getByLabel('Message', { exact: true }).fill('Please review the new community contributions.');
  await page.getByLabel('Audience', { exact: true }).selectOption('manager');
  await page.getByRole('button', { name: 'Send announcement', exact: true }).click();
  await page.locator('.admin-review-item').filter({ hasText: 'Staff briefing' }).waitFor();
  const broadcast = page.locator('.admin-review-item').filter({ hasText: 'Staff briefing' });
  assert((await broadcast.innerText()).includes('Manager'), 'Announcement audience supports assigned staff roles');
  await broadcast.getByRole('button', { name: 'Withdraw', exact: true }).click();
  await broadcast.getByRole('button', { name: 'Restore', exact: true }).waitFor(); checks.push('Announcement broadcast history and withdrawal work');
  await go('/admin/roles');
  assert((await page.locator('tbody tr').filter({ hasText: 'sheriff' }).innerText()).includes('Protected'), 'Primary and current administrator role are protected in UI');
  await page.getByRole('button', { name: 'Assign a staff role', exact: true }).click();
  await page.getByLabel('Role for cipher').selectOption('manager');
  await Promise.all([page.waitForResponse(response => response.url().endsWith('/role') && response.request().method() === 'PATCH'), page.locator('tbody tr').filter({ hasText: 'cipher' }).getByRole('button', { name: 'Save role', exact: true }).click()]);
  assert((await state()).requests.some(r => r.path.endsWith('/role') && r.body.role === 'manager'), 'Administrator can assign manager role');
  await go('/admin/system');
  await page.getByRole('heading', { name: 'Backend status', exact: true }).waitFor();
  assert((await page.locator('.admin-system-details').first().innerText()).includes('ec2-backend-fixture'), 'Backend status reports host data returned by API');
