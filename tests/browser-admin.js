  await fixture({ role: 'editor' }); await go('/admin/challenges');
  assert(await page.getByRole('button', { name: 'Publish', exact: true }).count() === 0, 'Editor cannot approve other submissions');
  await fixture({ role: 'user' }); await go('/admin'); await page.waitForURL('**/dashboard'); checks.push('Member cannot enter administration');
  await fixture({ role: 'admin', authenticated: false }); await go('/admin'); await page.waitForURL('**/login'); checks.push('Anonymous admin entry redirects to login');
  await page.getByLabel('Username or email').fill('sheriff'); await page.getByLabel('Password', { exact: true }).fill('FixturePassword1!');
  await page.getByRole('button', { name: 'Log in', exact: true }).click(); await page.waitForURL('**/admin'); checks.push('Administrator login lands directly in administration');
  await go('/admin/security');
  await page.getByLabel('Current password', { exact: true }).fill('FixturePassword1!');
  await page.getByLabel('New password', { exact: true }).fill('UpdatedPassword1!');
  await page.getByLabel('Confirm new password', { exact: true }).fill('UpdatedPassword1!');
  await page.getByRole('button', { name: 'Update password & sign out', exact: true }).click(); await page.waitForURL('**/login'); checks.push('Password change ends the staff session');
