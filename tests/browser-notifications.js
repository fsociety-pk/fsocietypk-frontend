// Run after generated browser-fixtures.js. HTTP and WebSocket data are fixtures.
async page => {
  const checks = [];
  const check = (value, name) => { if (!value) throw Error(name); checks.push(name); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const member = '507f1f77bcf86cd799439011';
  let identity = member, role = 'user', socket, release, releaseList, onConnected, hold = false, holdList = false, fail = false, failList = false;
  let serial = 0, reads = 0;
  const make = (read = false) => ({ _id: (100 + ++serial).toString(16).padStart(24, '0'), userId: member, type: 'system', title: `Update ${serial}`, message: 'A notification test message.', read, createdAt: new Date(Date.now() + serial).toISOString() });
  let records = [make(), make(), make(true)];
  const first = records[0]._id;
  await page.routeWebSocket('**/socket.io/**', ws => {
    ws.send('0' + JSON.stringify({ sid: `notifications-${serial}`, upgrades: [], pingInterval: 300000, pingTimeout: 20000, maxPayload: 1000000 }));
    ws.onMessage(message => {
      if (message === '40') { ws.send('40' + JSON.stringify({ sid: `notifications-${serial}` })); socket = ws; onConnected?.(); }
    });
  });
  await page.route('**/api/**', async route => {
    const request = route.request(), path = new URL(request.url()).pathname;
    const json = (data, status = 200) => route.fulfill({ status, contentType: 'application/json', body: JSON.stringify({ success: status < 400, data, message: status >= 400 ? 'Temporary fixture failure' : 'OK' }) });
    if (path.endsWith('/auth/me')) return json({ _id: identity, username: 'cipher', role, score: 0, solvedChallenges: [] });
    if (!path.includes('/notifications')) return route.fallback();
    if (request.method() === 'GET') {
      if (path.endsWith('/unread-count')) return json({ unreadCount: records.filter(item => item.userId === identity && !item.read).length });
      reads++;
      if (holdList) await new Promise(resolve => { releaseList = resolve; });
      return failList ? json(null, 503) : json(records.filter(item => item.userId === identity));
    }
    const input = request.postDataJSON() || {};
    if (hold) await new Promise(resolve => { release = resolve; });
    if (fail) return json(null, 503);
    if (path.endsWith('/read/all')) records = records.map(item => input.ids.includes(item._id) ? { ...item, read: true } : item);
    else if (request.method() === 'PATCH') records = records.map(item => path.includes(item._id) ? { ...item, read: input.read } : item);
    else if (path.endsWith('/notifications')) records = records.filter(item => !input.ids.includes(item._id));
    else records = records.filter(item => !path.includes(item._id));
    return json(null);
  });
  const badge = page.locator('.notification-bell .notification-count');
  const card = id => page.locator(`[data-notification-id="${id}"]`);
  const settled = async () => page.waitForFunction(() => !document.querySelector('[aria-busy="true"]'));
  const finish = async () => { hold = false; release(); await settled(); };
  const arrive = async () => {
    const item = make(); records = [item, ...records];
    socket.send('42' + JSON.stringify(['notificationCreated', item]));
    await card(item._id).waitFor();
    return item;
  };
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1600, height: 900 });
  await page.goto('http://fsociety.test/notifications');
  await page.getByRole('heading', { name: 'Notifications', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('.notification-count')?.textContent === '2');
  check(await badge.innerText() === '2', 'Bell shows the exact unread number');
  check(await page.locator('.notification-dot').count() === 0, 'Bell replaces the dot with a count');
  check(await page.locator('.notification-bell-symbol.has-arrival').count() === 0, 'Existing unread items do not ring on first load');
  const team = page.locator('.app-sidebar .sidebar-team-link');
  check(await team.locator('span').evaluate(el => el.getBoundingClientRect().height < 30), 'Sidebar team label fits one line');
  check(await team.evaluate(el => !!(document.querySelector('.app-sidebar nav[aria-label="Personal"]').compareDocumentPosition(el) & Node.DOCUMENT_POSITION_FOLLOWING)), 'Team link appears after the personal navigation');
  check(await team.getAttribute('target') === '_blank' && (await team.getAttribute('rel')).includes('noopener'), 'Moved team link preserves safe external navigation');
  await page.setViewportSize({ width: 1600, height: 682 });
  check(await team.evaluate(el => { const r = el.getBoundingClientRect(); return r.top >= 0 && r.bottom <= innerHeight; }), 'Team link stays visible above Sign out on a short desktop screen');
  await page.setViewportSize({ width: 1600, height: 900 });
  await page.getByRole('button', { name: 'Unread', exact: true }).click();
  hold = true;
  await card(first).getByRole('button', { name: 'Mark as read', exact: true }).click();
  await card(first).waitFor({ state: 'detached', timeout: 800 });
  check(await badge.innerText() === '1', 'Read click updates list and badge before a slow save completes');
  await finish();
  const beforeFilter = reads;
  await page.getByRole('button', { name: 'Read', exact: true }).click();
  await card(first).waitFor();
  check(reads === beforeFilter, 'Read/unread filters do not wait for extra requests');
  hold = true;
  await card(first).getByRole('button', { name: 'Mark as unread', exact: true }).click();
  await card(first).waitFor({ state: 'detached', timeout: 800 });
  check(await badge.innerText() === '2', 'Mark unread updates immediately and removes the item from the Read filter');
  check(await page.locator('.notification-bell-symbol.has-arrival').count() === 0, 'Marking an existing item unread does not trigger a new-arrival animation');
  await finish();
  await page.getByRole('button', { name: 'All', exact: true }).click();
  hold = true; fail = true;
  await card(first).getByRole('button', { name: 'Mark as read', exact: true }).click();
  await page.waitForFunction(id => document.querySelector(`[data-notification-id="${id}"]`)?.getAttribute('data-read') === 'true', first);
  const incoming = await arrive();
  check(await badge.innerText() === '2', 'Arrival updates the optimistic unread count while a save is pending');
  socket.send('42' + JSON.stringify(['notificationCreated', incoming]));
  await page.waitForTimeout(50);
  check(await badge.innerText() === '2' && await card(incoming._id).count() === 1, 'Duplicate live events do not double count or duplicate rows');
  check(await page.locator('.notification-bell-symbol.has-arrival').count() === 1, 'New incoming notification starts the bell animation');
  await finish(); fail = false;
  await page.waitForFunction(id => document.querySelector(`[data-notification-id="${id}"]`)?.getAttribute('data-read') === 'false', first);
  check(await badge.innerText() === '3' && await card(incoming._id).count() === 1, 'Failed read restores its state and preserves the incoming notification');
  await page.getByText('Could not save that change. Please try again.', { exact: true }).waitFor();
  hold = true;
  await page.getByRole('button', { name: 'Mark all as read', exact: true }).click();
  await badge.waitFor({ state: 'detached', timeout: 800 });
  const afterReadAll = await arrive();
  check(await badge.innerText() === '1', 'Arrival during Mark all as read stays unread');
  await finish();
  check(await card(afterReadAll._id).getAttribute('data-read') === 'false', 'Bulk read response preserves the new arrival');
  hold = true;
  await page.getByRole('button', { name: 'Clear all', exact: true }).click();
  await page.locator('.notification-card').waitFor({ state: 'detached', timeout: 800 });
  const afterClear = await arrive();
  await finish();
  check(await card(afterClear._id).count() === 1 && await badge.innerText() === '1', 'Clear all preserves notifications received during the request');
  hold = true;
  await card(afterClear._id).getByRole('button', { name: 'Delete notification' }).click();
  await card(afterClear._id).waitFor({ state: 'detached', timeout: 800 });
  check(await badge.count() === 0, 'Delete immediately removes the item and its unread count');
  await finish();
  await page.reload();
  await page.getByText('No notifications yet', { exact: true }).waitFor();
  check(await badge.count() === 0, 'Saved read/delete changes persist after reload');
  records = Array.from({ length: 103 }, () => make());
  await page.reload();
  await page.waitForFunction(() => document.querySelector('.notification-count')?.textContent === '99+');
  check(await page.locator('.notification-bell').getAttribute('aria-label') === 'Notifications, 103 unread', 'Large counts cap visually at 99+ and retain the full accessible number');
  for (const width of [320, 390, 768, 1024, 1600]) {
    await page.setViewportSize({ width, height: 900 });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px notification page has no horizontal overflow`);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/notifications-member-phone.png' });
  await page.getByRole('button', { name: 'Switch to dark theme' }).click();
  await page.screenshot({ path: '/tmp/notifications-member-phone-dark.png' });
  await page.getByRole('button', { name: 'Switch to light theme' }).click();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await arrive();
  check(await page.locator('.notification-bell-symbol').evaluate(el => getComputedStyle(el).animationName === 'none'), 'Reduced motion disables the bell animation');
  await page.setViewportSize({ width: 1600, height: 900 });
  await page.screenshot({ path: '/tmp/notifications-member-desktop.png' });
  role = 'admin';
  await page.goto('http://fsociety.test/admin/notifications');
  await page.waitForFunction(() => document.querySelector('.notification-count')?.textContent === '99+');
  check((await page.locator('.notification-bell').getAttribute('aria-label')).startsWith('Admin notifications,'), 'Staff header uses the same live counted bell');
  identity = '507f1f77bcf86cd799439012'; role = 'user';
  await page.goto('http://fsociety.test/notifications');
  await page.getByText('No notifications yet', { exact: true }).waitFor();
  check(await badge.count() === 0, 'Changing accounts does not retain another member’s inbox or count');
  failList = true;
  await page.reload();
  await page.getByRole('button', { name: 'Try again', exact: true }).waitFor();
  check(await page.getByText('No notifications yet', { exact: true }).count() === 0, 'Failed inbox fetch shows retry instead of a misleading empty inbox');
  failList = false;
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await page.getByText('No notifications yet', { exact: true }).waitFor();
  identity = member;
  records = [make(), make()];
  holdList = true;
  const connected = new Promise(resolve => { onConnected = resolve; });
  await page.reload();
  await page.getByRole('heading', { name: 'Notifications', exact: true }).waitFor();
  await connected;
  holdList = false;
  const duringLoad = await arrive();
  releaseList?.();
  await page.waitForFunction(() => document.querySelectorAll('.notification-card').length === 3);
  check(await card(duringLoad._id).count() === 1, 'Arrival during initial loading recovers the full inbox without waiting for the poll');
  records = records.map(item => ({ ...item, read: true }));
  socket.send('42' + JSON.stringify(['notificationsChanged']));
  await badge.waitFor({ state: 'detached' });
  check(await page.locator('.notification-card[data-read="false"]').count() === 0, 'Read changes from another tab refresh both the inbox and count');
  check(errors.length === 0, 'No browser runtime errors');
  return { passed: checks.length, checks };
}
